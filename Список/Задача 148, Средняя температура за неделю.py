print('Задача 148, Средняя температура за неделю')

A = ['Понедельник','Вторник','Среда','Четверг','Пятница','Суббота','Воскресенье']

count = 0
for x in A:
    print('{} ->'.format(x), end = '')
    B = int(input())
    count +=B
print('Средняя температура за неделю = {:.1f} градусов по цельсию'.format(count / len(A)))    


