print('Линейная Апроксимация функции')


def aproxim(X,Y,X_):
    Sum_X = 0
    Sum_Y = 0
    Sum_X2 = 0
    Sum_XY = 0
        
    for i in range(N):
        Sum_X += X[i]
        Sum_Y += Y[i]
        Sum_X2 += X[i] * X[i]
        Sum_XY += X[i] * Y[i]
    a = (N *  Sum_XY - Sum_X * Sum_Y) / (N * Sum_X2 - Sum_X ** 2 )  
    b = 1/N * (Sum_Y - a * Sum_X)
    y = a * X_ + b
    print('Коэфициент a апроксимирующей функции равен',a)
    print('Коэфициент b апроксимирующей функции равен',b)
    return y


N = int(input('Введите количество точек: '))

