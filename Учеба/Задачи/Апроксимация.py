# =============================================================================


X = [2, 6, 10, 14, 18]
Y = [9, 10, 12, 19, 20]

X_ = int(input('Введите значение X_: '))

Y_ = aproxim(X,Y,X_)

print('Значение апроксимирующей функции в точке X={} равно {}'.format(X_,Y_))